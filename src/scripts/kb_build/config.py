# 지식베이스 폴더 경로 — `NN_이름` 의 번호는 재번호로 바뀜, 이름으로만 탐색

REPO = agent_config.REPO_ROOT


def kb_folder(name: str) -> Path:
    """`NN_<name>` 최상위 폴더 탐색(번호 무관). 없거나 둘 이상이면 예외 — 빈 경로로 «0건» 결과 방지."""
    hits = sorted(d for d in REPO.glob(f"*_{name}") if d.is_dir())
    if not hits:
        raise FileNotFoundError(
            f"지식베이스 폴더를 찾지 못했다: *_{name} (탐색 위치: {REPO})"
        )
    if len(hits) > 1:
        raise RuntimeError(f"*_{name} 에 해당하는 폴더가 둘 이상이다: {[h.name for h in hits]}")
    return hits[0]


