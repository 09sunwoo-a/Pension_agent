# 지식베이스 폴더 경로 — 번호 접두에 의존하지 않는다
#
# 저장소 최상위 폴더는 `NN_이름` 형태이고, NN 은 폴더가 추가될 때마다 밀린다. 실제로 두 번
# 밀렸다 — `01_사내가이드_연금사업부` → `01_행내가이드문서_…`(아래 PATH_REMAP 이 그 흔적),
