# 하드코딩하고 있어서 변환기가 FileNotFoundError 로 죽었고, 생성 JSON 의 `source.locator`
# 543 건이 존재하지 않는 경로를 가리키게 됐다(테스트는 생성물만 읽어서 전부 통과했다).
#
# 그래서 번호를 빼고 **이름으로** 찾는다. 세 번째 재번호가 와도 깨지지 않는다.
# ─────────────────────────────────────────────────────────────

REPO = agent_config.REPO_ROOT


def kb_folder(name: str) -> Path:
    """`NN_<name>` 최상위 폴더를 번호와 무관하게 찾는다.

    없거나 둘 이상이면 그 자리에서 실패한다 — 조용히 빈 경로를 돌려주면 변환기가 "항목 0건"
    이라는 그럴듯한 결과를 내고, 그게 정상인지 아닌지 아무도 모른다.
    """
    hits = sorted(d for d in REPO.glob(f"*_{name}") if d.is_dir())
    if not hits:
        raise FileNotFoundError(
            f"지식베이스 폴더를 찾지 못했다: *_{name} (탐색 위치: {REPO})"
        )
    if len(hits) > 1:
        raise RuntimeError(f"*_{name} 에 해당하는 폴더가 둘 이상이다: {[h.name for h in hits]}")
    return hits[0]


