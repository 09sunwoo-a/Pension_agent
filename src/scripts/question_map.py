import re as _re

#: 이름 + 그 뒤에 붙은 값(「오세훈2」·「박지민16.5」처럼 대조 행이 쓰는 표기).
_PIN_RE = _re.compile("(" + "|".join(PIN) + r")(\d*(?:\.\d+)?)")
#: 그 뒤가 이미 kb-pin 인가. `pin()` 이 **두 번 돌아도 같아야** 하기 때문에 본다.
_PINNED = _re.compile(r" ?\d{6}-\d{7}")


def pin(text):
    """이름 옆에 kb-pin 을 붙인다 — 그 번호를 그대로 `-c` 인자로 쓸 수 있게.

    **두 번 돌려도 같아야 한다.** 이 함수는 xlsx 를 쓸 때(원본 이름)와 다시 읽을 때(이미
    pin 이 붙은 글)에 **둘 다** 불리고, 그 결과가 실측 답변을 따라오게 하는 키다(`_key`).
    한쪽만 달라지면 답이 조용히 사라진다.

    예전에는 「이미 붙었나」를 부정 선읽기로 재서 이름 뒤에 **값이 붙은 표기**에서 깨졌다 —
    「오세훈2 193482-6012375」는 `\\d*` 가 «2» 를 먹으면 선읽기가 pin 을 보고 물러서는데,
    정규식이 `\\d*`=«» 로 되짚으면 이번에는 뒤가 «2 193482…» 라 pin 으로 안 보여 통과한다.
    그래서 pin 이 한 번 더 붙고 키가 어긋났다 — 고객별 대조 4행이 그렇게 답을 잃었다
    (2026-09-21 실측: 155·156·158·159. 값이 안 붙은 「송도윤 ↔ 김서연」 행은 멀쩡했다).
    지금은 되짚기가 없는 자리에서 **매치 뒤의 글**을 직접 본다.
    """
    def _put(m):
        if _PINNED.match(text, m.end()):
            return m.group(0)
        return f"{m.group(0)} {PIN[m.group(1)]}"
    return _PIN_RE.sub(_put, text)


