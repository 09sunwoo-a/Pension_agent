def _carry_answers(path):
    """기존 xlsx 의 답·앞 턴·출처를 키별로 수집. 파일 없으면 빈 dict."""
    if not path.is_file():
        return {}
    try:
        from openpyxl import load_workbook
    except ModuleNotFoundError:
        return {}
    ws = load_workbook(path, read_only=True).active
    head_row, head = find_head(ws)
    if not head:
        return {}
    try:
        ci, qi, wi = (head.index(x) for x in ("항목", "질문", "대상 고객"))
        # 옛 열 이름도 읽음 — 새 이름만 찾으면 쌓인 답 전부 소실
        ai = next(head.index(x) for x in (ANS_COL, "실측 답변") if x in head)
    except (ValueError, StopIteration):
        return {}
    si = head.index(SRC_COL) if SRC_COL in head else None
    pi = next((head.index(x) for x in ("앞 질문과 답", "앞 턴") if x in head), None)
    # 항목·질문 칸은 세로 병합 — 앞 값을 이어 읽어야 키 일치
    out, item, q = {}, "", ""
    for r in ws.iter_rows(min_row=head_row + 1, values_only=True):
        item = str(r[ci]) if r[ci] else item
        if r[qi]:
            # 앞 턴을 잘라 키로 사용(앞 턴 답변은 실행마다 달라짐)
            q, cell_pre = bare_question(r[qi]), _pre_in_cell(r[qi])
        else:
            cell_pre = ""
        pre = cell_pre or ((r[pi] or "") if pi is not None and pi < len(r) else "")
        src = (r[si] or "") if si is not None and si < len(r) else ""
        if r[ai] or pre or src:
            out[_key(item, q, str(r[wi]))] = (r[ai] or "", pre, src)
    return out

#: 요건 코드 → 한글 이름. 이름은 `customer.CONDS` 에서 읽음 — 여기 복사 금지.
def _conds_ko(codes: str) -> str:
    """「dep, idl」 → 한글 요건명. 코드 아닌 글·CONDS 에 없는 코드는 그대로 둠(누락 오인 방지)."""
    from pension_agent.tools.customer_solution.customer import CONDS
    parts = [c.strip() for c in str(codes or "").split(",") if c.strip()]
    if not parts or not all(p in CONDS for p in parts):
        return str(codes or "")
    return " · ".join(CONDS[p] for p in parts)


