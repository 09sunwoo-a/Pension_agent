def _groups():
    by = {}
    for r in R:
        by.setdefault(r[0], []).append(r)
    unknown = set(by) - set(ORDER)
    if unknown:
        raise SystemExit("ORDER 에 없는 항목: " + repr(sorted(unknown)))
    out, n = [], 0
    for num, item in enumerate(ORDER, 1):
        rows = []
        for r in by.get(item, ()):
            n += 1
            rows.append((n, r))
        out.append((SECTION_OF[item], f"{num}. {item}", rows))
    return out


def branch_label(item, q, who):
    """같은 항목에서 되풀이되는 질문 행의 갈래 이름(대상 고객 칸 머리)."""
    bare = item.split(". ", 1)[-1]      # 렌더 쪽 항목에는 번호가 붙어 있다
    same = [r for r in R if r[0] == bare and r[1] == q]
    if len(same) < 2:
        return ""
    return who.split(" — ")[0].strip()


def point_of(item, q, who, point):
    label = branch_label(item, q, who)
    return f"〔{label}〕 {point}" if label else point


def counts():
    """갱신 보고용 수 — (보여주는 질문 수, 출처별, 등급별)."""
    from collections import Counter
    shown_n = sum(1 for sec, item, rows in _groups()
                  for num, r in rows if shown(item, r[1]))
    return (shown_n,
            Counter("신규" if not r[5] else "기존 대본" for r in R),
            Counter(r[4] for r in R))


#: 보이는 「고객」 열 글 — kb-pin·군 설명을 떼고 이름만. 괄호 값은 유지(대조 축).
def _who_short(who: str) -> str:
    text = _re.sub(r"\s*\d{6}-\d{7}", "", str(who or "")).strip()
    if " — " in text:
        head, _, tail = text.partition(" — ")
        tail = tail.strip()
        # 「… — 예: 이름」은 군 이름, 「… — A ↔ B」는 맞세운 둘
        return head.strip() if tail.startswith("예:") else tail
    return text


#: 행 높이 계산 — 엑셀은 병합 칸이 있는 행 높이를 자동 조정 안 함. 상한 80줄(잘리는 행 0).
_LINE_PT, _MIN_LINES, _MAX_LINES = 13.5, 2, 80
#: 아래 column_dimensions 폭과 일치 필수. 1.08 = 한글이 반각 열 너비보다 덜 들어가는 보정.
_W_FUDGE = 1.08
_ANSWER_W, _QUESTION_W, _SRC_W = 72, 52, 30


def _row_height(question: str, answer: str, src: str = "") -> float:
    def lines(text: str, width: int) -> int:
        w = max(8, int(width / _W_FUDGE))
        n = 0
        for part in str(text or "").split("\n"):
            n += max(1, -(-len(part) // w))         # 올림 나눗셈
        return n
    need = max(lines(answer, _ANSWER_W), lines(question, _QUESTION_W),
               lines(src, _SRC_W))
    return round(min(max(need, _MIN_LINES), _MAX_LINES) * _LINE_PT, 1)


