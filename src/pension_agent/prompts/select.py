from __future__ import annotations


# ─────────────────────────────────────────────────────────────
# llm_select 노드용 — 카드 선택 1차 (n-gram 은 이게 0건일 때의 폴백)
#
# 카드 목록을 통째로 싣지 않고 두 단계로 나눈다 — 행내 모델(gemma4-31b·
# dna3.0-35b)의 컨텍스트에 30k 토큰짜리 전체 목록을 실을 수 없기 때문이다.
# ① BUCKET_PROMPT 로 버킷(주제 묶음)을 고르고 ② SELECT_PROMPT 로 그 버킷
# 안의 카드만 보여주고 id 를 고르게 한다. 두 호출 모두 2k 토큰 아래다.
# ─────────────────────────────────────────────────────────────

BUCKET_PROMPT = """아래는 등록된 카드가 어떤 묶음으로 나뉘어 있는지 보여주는 목록이다.
각 줄 앞의 코드(P01, R02 …)가 묶음 식별자다.

{catalog}

직원 질문: {question}

이 질문의 답이 들어 있을 가능성이 높은 묶음의 코드를 최대 3개 골라 JSON 배열로만
출력하라. 목록에 있는 코드만 쓴다. 맞는 묶음이 없으면 빈 배열 []을 출력한다.
설명·코드펜스 없이 JSON 배열만 출력한다.

예: ["P02", "P07"]"""


SELECT_PROMPT = """아래는 앞서 고른 묶음에 들어 있는 카드 목록이다(대괄호 안이 id).
목록에 없는 카드는 존재하지 않으니 만들어내지 마라.

{card_slice}

직원 질문: {question}

이 질문에 실제로 답이 될 수 있는 카드의 id를 관련도 높은 순으로 최대 3개 골라
JSON 배열로만 출력하라. 목록에 있는 id만 쓴다. 맞는 카드가 하나도 없으면 빈
배열 []을 출력한다. 설명·코드펜스 없이 JSON 배열만 출력한다.

예: ["pitch.k03.029", "proc.001"]"""
