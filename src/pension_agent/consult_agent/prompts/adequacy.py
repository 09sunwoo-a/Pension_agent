# 적합성 게이트(tools.fits_question) — 고른 근거가 질문에 답이 되는지 판정
#
# **재료 종류를 가리지 않는다**(CLAUDE.md §5). 예전에는 화법에만 있었고, 값·절차·정의·
# 방법론·현장 관찰은 검색 점수만으로 채택됐다 — 주제어만 겹친 카드를 거를 장치가 없었다.
# "틀리지 않은 답"과 "질문에 답이 되는 답"은 다르고, §6 의 점검은 전부 틀린 것을 막는
# 검사라 적절성을 보증하지 못한다. 그 몫이 여기다.
#
# **계획이 무엇을 찾는 중인지도 함께 준다.** 게이트는 「애매하면 뺀다」로 판정하는데,
# 직원 질문만 보면 "이 고객 무슨 상품 추천해주지?" 같은 **고객 특정 질문**에 대해
# 「투자성향별 포트폴리오」 같은 **일반 자료**가 전부 "이 고객에 대한 답이 아니다"로
# 떨어진다 — 계획은 그 표를 고객 성향에 대조하려고 부른 것인데 그 의도가 게이트에는
# 안 보인다. 실제로 상품 질의가 재료 0건으로 세 바퀴를 돌고 브리핑 덤프로 끝났다.
# 판단 재료가 모자라 맞는 카드가 전멸하는 것은 gap 21(이전 대화를 못 봄)과 같은 부류다.
#
# 곁가지로 `tools.run` 의 원문 재검색이 이걸로 **비로소 의미를 갖는다.** 재검색은 질의를
# 바꿔 다시 찾는데 게이트는 두 번 다 직원 질문만 보고 판정했다 — 같은 후보에 같은 질문이라
# 판정이 바뀔 수 없었고, LLM 호출 한 번이 통째로 낭비됐다.
#
# ━━ 갈래를 여기서 적는 이유 ━━
# 후보 목록 **전체**를 보는 곳이 여기뿐이다. 「이 둘은 조건이 갈려서 답이 달라진다」는
# 후보를 나란히 놓아야 보이는 사실인데, 되묻기 판정(nodes/clarify.py)이 받는 것은 채택이
# 끝난 원장이라 무엇이 후보였는지가 남아 있지 않다. 그래서 축과 선택지만 `branches` 로
# 넘긴다(tools/adequacy.py::record_branches).
#
# **판정은 «남긴 후보» 위에서 한다.** 처음에는 「빼려는 후보들이 서로 갈래면 빼지 말고
# 남겨라」로 적었다. 그러면 갈래 절이 **뺄 후보가 있는 턴에만** 읽힌다 — 실측 11턴 내내
# `branches` 가 한 번도 안 찍힌 이유가 이것이다. 갈래가 걸리는 질문일수록 갈래마다 답이
# 되는 카드가 **전부 맞는 카드**라 하나도 안 빠진다. 「수수료 얼마야」의 후보가 그렇다:
# 사용자부담금 구간 · 가입자부담금 구간 · 퇴직금 5천만원 비대면 면제 · 대면→비대면 인하가
# 넷 다 그 질문의 답이고, 넷 다 남고, 그래서 갈래를 아무도 안 적었다.
