#: 지금 도는 판. `reps review` · 문서(`docs/DEMO_REVIEW.md`)가 가리키는 것이 이 판이다.
LATEST = REVIEW[-1].name


def _apply(blocks: tuple[Block, ...], edit: Edit) -> tuple[Block, ...]:
    """변경 하나를 적용한다. 대상 라벨이 없으면 실패한다 — 조용히 지나가면 이력이 거짓말한다."""
    anchor = edit.after if edit.op == "더함" else edit.label
    hit = False
    out: list[Block] = []
    for no, sees, customer, turns in blocks:
        new: list[Turn] = []
        for label, question in turns:
            if edit.op in ("고침", "뺌") and label == edit.label:
                hit = True
                if edit.op == "고침":
                    new.append((label, edit.question))
                continue
            new.append((label, question))
            if edit.op == "더함" and label == anchor:
                hit = True
                new.append((edit.label, edit.question))
        out.append((no, sees, customer, tuple(new)))
    if not hit:
        raise ValueError(f"{edit.op} 대상 턴이 없습니다: {anchor} — 버전 이력의 라벨이 어긋났습니다")
    return tuple(out)


def version_names() -> list[str]:
    return [v.name for v in REVIEW]


def review_blocks(version: str | None = None) -> tuple[Block, ...]:
    """그 판의 대본. 첫 판에 변경을 순서대로 접어서 만든다."""
    target = version or LATEST
    if target not in version_names():
        raise KeyError(target)
    blocks = REVIEW_BASE
    for v in REVIEW:
        for edit in v.edits:
            blocks = _apply(blocks, edit)
        if v.name == target:
            return blocks
    raise KeyError(target)          # 도달하지 않는다 — 위에서 이름을 검사했다


def changes_between(older: str, newer: str) -> list[tuple[Version, Edit]]:
    """두 판 사이의 변경을 순서대로. `older` 다음 판부터 `newer` 까지다."""
    names = version_names()
    if older not in names:
        raise KeyError(older)
    if newer not in names:
        raise KeyError(newer)
    lo, hi = names.index(older), names.index(newer)
    if lo > hi:
        lo, hi = hi, lo
    return [(v, e) for v in REVIEW[lo + 1:hi + 1] for e in v.edits]


def questions_of(version: str | None = None) -> dict[str, str]:
    """라벨 → 질문. 두 판을 라벨로 맞대볼 때 쓴다."""
    return {label: q for _, _, _, turns in review_blocks(version) for label, q in turns}
