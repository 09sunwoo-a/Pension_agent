"""회귀 테스트 패키지.

**«오늘»을 고정하는 것은 회귀 테스트의 요건이다 — 이 패키지를 지나는 모든 실행의 요건이
아니다.** `customer.today()` 는 기본이 실제 날짜라, 고정하지 않으면 만기 잔여일수·미접촉
일수·연말까지 남은 일수가 실행일마다 달라지고 600건 넘는 단언이 «어제는 통과했는데 오늘은
실패»로 흔들린다. 고정값은 원장 스냅샷 기준일(`customer.AS_OF`)과 같은 날로 둔다 — 시연
데이터가 그날 찍힌 값이므로 그 위에서 세운 기존 단언(만기 D-17, 미접촉 88일 …)이 그대로
성립한다.

**고정은 회귀 테스트 모듈이 스스로 건다**(`pin_today()`를 맨 위에서 부른다). 예전에는 이
파일이 임포트만으로 걸었는데, 그러면 이 패키지 **안에 사는 다른 것들까지** 고정을 물려받는다 —
리허설 러너(`tests.debug.reps`)·디버그 CLI(`tests.debug`)가 그랬고, 실제 날짜로 도는 줄 알고
돌린 사람이 원장 기준일 기준의 경과일을 지어낸 수치로 의심했다(2026-09-07). Streamlit 화면도
디버그 모드를 켜는 순간 `tests.debug` 를 임포트해 «오늘»이 조용히 과거로 밀렸고, `app.py` 는
그것을 막으려고 자기가 먼저 날짜를 채워 넣고 있었다. 지금은 **거는 쪽이 걸고 싶다고 말한다** —
그 우회들이 전부 필요 없어졌다.

두 값이 갈리면 `tests/test_infra.py` 가 잡는다(고정값 = AS_OF · 회귀 모듈이 전부 부른다).
날짜 산술 자체는 특정 날짜를 명시해 검증한다(같은 파일 「오늘·기준일」 절) — 고정해 둔
하루로만 보면 세는 법의 오류를 못 잡는다.
"""

from __future__ import annotations

import os

#: customer.AS_OF 와 같은 날. 여기서 import 해 오지 않는 이유는 이 대입이 그 모듈보다
#: **먼저** 일어나야 하기 때문이다(customer 는 임포트 시점에 PERSONAS 를 만든다).
PINNED_TODAY = "2026-08-24"

TODAY_ENV = "PENSION_TODAY"     # pension_agent.clock.TODAY_ENV — 위와 같은 이유로 복사한다


def pin_today() -> None:
    """이 회귀 스위트가 도는 «오늘»을 원장 기준일로 고정한다.

    **`pension_agent` 를 임포트하기 전에 부른다.** `customer` 는 임포트 시점에 PERSONAS 를
    만들면서 잔여일수·경과일을 그때의 «오늘»로 계산한다 — 그 뒤에 걸어도 그 값들은 이미
    굳었다. 그래서 회귀 모듈의 맨 윗줄이다.

    밖에서 준 값은 덮지 않는다 — 특정 날짜로 스위트를 돌려 보는 경로를 남긴다.
    """
    if not os.environ.get(TODAY_ENV, "").strip():
        os.environ[TODAY_ENV] = PINNED_TODAY
