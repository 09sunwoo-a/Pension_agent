def rank_of(value, arr):
    """코호트 분위 배열에서 값의 백분위(하위 %)를 선형보간으로 산출"""
    q=PCT_Q
    if value<=arr[0]: return round(q[0]*value/arr[0],1)
    for i in range(len(arr)-1):
        if arr[i]<=value<=arr[i+1]:
            f=(value-arr[i])/(arr[i+1]-arr[i])
            return round(q[i]+f*(q[i+1]-q[i]),1)
    return 99.9

