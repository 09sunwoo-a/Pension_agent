def load():
    units = {}
    for f in ["20_지식유닛.yaml", "21_지식유닛_화법.yaml", "22_지식유닛_팩트_절차_금지.yaml"]:
        for u in yaml.safe_load(open(os.path.join(HERE, f)))["units"]:
            units[u["id"]] = u
